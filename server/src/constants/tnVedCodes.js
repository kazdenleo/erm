const byCode = new Map(TN_VED_CODES.map((x) => [x.code, x]));

export function findTnVedByCode(code) {
  const c = String(code || '').replace(/\D/g, '');
  if (!c) return null;
  return byCode.get(c) || byCode.get(c.padEnd(10, '0').slice(0, 10)) || null;
}

export function searchTnVedCodes(query = '', limit = 50) {
  const q = String(query || '').trim().toLowerCase().replace(/\s+/g, ' ');
  const max = Math.min(Math.max(Number(limit) || 50, 1), 200);
  if (!q) return TN_VED_CODES.slice(0, max);
  const digits = q.replace(/\D/g, '');
  const results = [];
  for (const row of TN_VED_CODES) {
    const codeHit = digits && row.code.includes(digits);
    const nameHit = row.name.toLowerCase().includes(q);
    if (codeHit || nameHit) {
      results.push(row);
      if (results.length >= max) break;
    }
  }
  return results;
}

export function isKnownTnVedCode(code) {
  return Boolean(findTnVedByCode(code));
}
