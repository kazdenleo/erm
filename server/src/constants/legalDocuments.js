/**
 * Тексты оферты и политики ПДн (шаблоны).
 * Реквизиты подставляются из env или плейсхолдеров — правятся позже.
 */

function env(name, fallback) {
  const v = process.env[name];
  return v != null && String(v).trim() !== '' ? String(v).trim() : fallback;
}

export function getLegalParty() {
  return {
    brand: env('LEGAL_BRAND', 'Программа Ирина'),
    company: env('LEGAL_COMPANY', 'ИП / ООО «Название» (укажите реквизиты)'),
    inn: env('LEGAL_INN', 'ИНН ______________'),
    ogrn: env('LEGAL_OGRN', 'ОГРН(ИП) ______________'),
    address: env('LEGAL_ADDRESS', 'адрес для корреспонденции'),
    email: env('LEGAL_EMAIL', 'support@example.com'),
    telegram: env('LEGAL_TELEGRAM', '@example_support'),
    domain: env('LEGAL_DOMAIN', 'dttrade.ru'),
    revisedAt: env('LEGAL_REVISED_AT', '2026-10-30'),
  };
}

